"""Shared local/Supabase sink for generic market odds.

The sink is deliberately non-fatal when called by the game odds collector:
moneylines remain available through the existing ``book_odds`` path if the new
table has not been migrated yet.
"""
from __future__ import annotations

from datetime import datetime, timezone
import hashlib
import player_store

player_store.register_table(
    "market_odds",
    """create table if not exists market_odds (
      odds_id integer primary key autoincrement, game_id text not null,
      captured_at text not null, bookmaker text not null, market text not null,
      selection text not null, player_id integer, line real, price_american integer not null,
      unique (game_id,captured_at,bookmaker,market,selection,player_id,line))""",
    ["odds_id"],
)


def moneyline_rows(games, captured_at: str | None = None) -> list[dict]:
    stamp = captured_at or datetime.now(timezone.utc).isoformat(timespec="seconds")
    rows = []
    for game in games:
        game_id = str(game.get("id") or game.get("game_id") or "")
        for selection, price_key, book_key in (
            ("home", "home_odds", "home_book"), ("away", "away_odds", "away_book")):
            price = game.get(price_key)
            book = game.get(book_key)
            if game_id and price is not None and book:
                row = {"game_id": game_id, "captured_at": stamp,
                             "bookmaker": book, "market": "moneyline",
                             "selection": selection, "player_id": None, "line": None,
                             "price_american": int(price)}
                # Supplying a deterministic identity makes the local sink
                # idempotent while remaining valid for GENERATED BY DEFAULT.
                key = "|".join(str(row.get(k)) for k in
                               ("game_id", "captured_at", "bookmaker", "market", "selection", "line"))
                row["odds_id"] = int(hashlib.sha256(key.encode()).hexdigest()[:15], 16)
                rows.append(row)
    return rows


def write_moneylines(games, *, conn=None) -> int:
    rows = moneyline_rows(games)
    return player_store.upsert("market_odds", rows, conn=conn)


def write_moneyline_rows(rows, *, conn=None) -> int:
    """Write already-normalized rows from an odds-provider response."""
    return player_store.upsert("market_odds", rows, conn=conn)
