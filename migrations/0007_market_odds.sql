-- Props-ready market odds.  Keep book_odds during the migration period.
create table if not exists public.market_odds (
  odds_id bigint generated by default as identity primary key,
  game_id text not null,
  captured_at timestamptz not null,
  bookmaker text not null,
  market text not null,
  selection text not null,
  player_id bigint,
  line numeric,
  price_american integer not null,
  constraint market_odds_unique unique
    (game_id, captured_at, bookmaker, market, selection, player_id, line)
);
alter table public.market_odds enable row level security;
